/** 注册前必须认可的协议编码（顺序即前端展示顺序）。 */
export const REGISTER_CONSENT_CODES = [
  REGISTRATION_AGREEMENT_CODE,
  PRIVACY_POLICY_CODE,
] as const;

export const defaultAgreementOf = (code: string) =>
  DEFAULT_AGREEMENTS.find((item) => item.code === code.trim().toUpperCase()) ||
  null;

/** 区块结构 → 纯文本正文：后台编辑器与公开页看到的都是同一份文本。 */
export const sectionsToText = (sections: DefaultAgreement['sections']) =>
  sections
    .map((section) =>
      [section.title, ...section.items.map((item) => `    ${item}`)].join('\n'),
    )
    .join('\n\n');

/** 后台「恢复为平台默认文本」与默认草案都用它生成正文。 */
export const defaultAgreementContent = (code: string) => {
  const doc = defaultAgreementOf(code);
  return doc ? sectionsToText(doc.sections) : '';
};
