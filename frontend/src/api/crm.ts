/** BI 问数 SSE：事件 status / result / error / done。 */
export async function streamBiAsk(
  body: Record<string, unknown>,
  onEvent: (event: string, data: Record<string, unknown>) => void,
  signal?: AbortSignal,
) {
  await streamSse("/api/backend/enterprise/bi/chat/stream", {
    body,
    signal,
    onEvent: (item) => {
      try {
        onEvent(item.event, JSON.parse(item.data) as Record<string, unknown>);
      } catch {
        // 忽略心跳/非 JSON 片段
      }
    },
  });
}

